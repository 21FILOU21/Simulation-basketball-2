const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const source = fs.readFileSync(path.join(__dirname, "..", "src", "real-game-mode.js"), "utf8");

assert.match(source, /function startGame\(\)/);
assert.match(source, /function runAI\(\)/, "The opposing team must be controlled by an AI turn.");
assert.match(source, /possession==="A"/, "The user should control the blue team.");
assert.match(source, /teamA\.length===5&&teamB\.length===5&&all\.every\(Boolean\)&&unique\.size===10/, "A valid match requires ten distinct players.");
assert.match(source, /function resolveShot\(/, "All shots must use the same resolution logic.");
assert.match(source, /green\?\.25/, "Shot timing must materially affect shot success.");
assert.match(source, /perimeterDefense/, "Perimeter defense must influence outside shots.");
assert.match(source, /interiorDefense/, "Interior defense must influence close-range shots.");
assert.match(source, /blockChance/, "Defenders must be able to block shots.");
assert.match(source, /stats\\[thief\\._rgmKey\\]\\.stl\\+\\+/, "Interceptions must award steals.");
assert.match(source, /lastPasser\._rgmKey/, "A made basket after a pass must award an assist.");
assert.match(source, /line\.fga\+\+/, "Shot attempts must be recorded.");
assert.match(source, /line\.threeA\+\+/, "Three-point attempts must be recorded.");
assert.match(source, /stats\[reb\._rgmKey\]\.reb\+\+/, "Offensive and defensive rebounds must be recorded.");
assert.match(source, /function renderGameOver\(/, "A completed match must show its final result.");
assert.match(source, /function renderStats\(/, "The match must expose a box score.");
assert.match(source, /PTS<\/th><th>REB<\/th><th>AST<\/th><th>STL<\/th><th>BLK<\/th><th>FG<\/th><th>3PT/, "The box score must show core basketball stats.");
assert.match(source, /shotClock=24/, "Each new possession must reset the shot clock.");
assert.match(source, /clock=720/, "Each quarter must start at twelve minutes.");
assert.match(source, /clock=300/, "Tied games must enter a five-minute overtime.");
assert.match(source, /rgmMeter\.onclick=takeShot/, "The user can click the timing bar directly.");
assert.match(source, /data-side=\"A\"/, "Blue players must be selectable as ball handlers.");
assert.match(source, /gameSprite\.shoot/, "Custom shooting sprites must be displayed during a shot.");
assert.match(source, /nba-sim-lab-real-game-sprites/, "Custom sprites must persist between sessions.");
assert.match(source, /new Set\(all\)/, "Duplicate player selections must be rejected.");
